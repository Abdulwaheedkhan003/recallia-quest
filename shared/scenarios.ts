/**
 * "What Would You Do?" — scenario catalogue shared by the server (AI engine) and the web app.
 *
 * Each scenario is DATA, not a script: it describes who the character is, what is really going on,
 * how they feel at the start and what may help. The AI engine (server/scenarios.ts) plays the
 * character turn by turn from this data plus the live conversation, so no reply is pre-written —
 * only the idea behind the opening line.
 *
 * These are practice situations for family carers. Not every person living with memory changes
 * experiences any of them, and every person is different.
 */

export type ScenarioMode = 'natural' | 'guided' | 'practice'
export type Difficulty = 1 | 2 | 3

export interface ScenarioCategory {
  id: string
  title: string
  emoji: string
  blurb: string
}

export interface Scenario {
  id: string
  category: string
  title: string
  /** One line shown on the scenario card. */
  description: string
  character: { name: string; role: string; age: number; portrait: string; pronoun: 'he' | 'she' }
  /** Relationship to the person practising, e.g. "your father". */
  relationship: string
  environment: string
  initialEmotion: string
  /** 0 = calm and settled, 100 = extremely distressed / activated. */
  initialIntensity: number
  /** What the carer sees before starting (short, second person). */
  context: string
  /** Hidden truth for the AI character: what is really going on, what they believe, what matters to them. */
  background: string
  /** The idea of the character's first line. The AI delivers it in its own words. */
  opening: string
  /** What the character needs to feel settled. */
  characterGoal: string
  /** Communication strategies that may help (used for coaching; never shown as "the answer"). */
  goals: string[]
  safetyNotes: string
  difficulty: Difficulty
  turns: { min: number; max: number }
}

